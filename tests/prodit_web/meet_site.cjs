// Автотест страницы /meet: регулярные встречи. Стенд: python3 tests/prodit_web/serve.py
// Запуск: PUPPETEER=<путь к node_modules/puppeteer-core> node tests/prodit_web/meet_site.cjs [папка скриншотов]
const puppeteer = require(process.env.PUPPETEER || 'puppeteer-core');
const crypto = require('crypto');
const BASE = 'http://127.0.0.1:18150';
const SP = process.argv[2] || require('os').tmpdir();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0; const check = (n, c) => { console.log((c ? '  ok  ' : 'FAIL  ') + n); if (!c) fails++; };
const body = Buffer.from(JSON.stringify({ e: 'site@acme.io', r: '', x: Math.floor(Date.now() / 1000) + 3600 })).toString('base64url');
const token = body + '.' + crypto.createHmac('sha256', 'mk').update(body).digest('hex');
const mine = async () => (await (await fetch(BASE + '/__test/meetings')).json()).filter((m) => m.organizer_email === 'site@acme.io' && m.recur);
(async () => {
  const br = await puppeteer.launch({ executablePath: process.env.CHROME || '/snap/bin/chromium', headless: 'new', args: ['--no-sandbox'] });
  const p = await br.newPage(); await p.setViewport({ width: 1280, height: 950 });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  p.on('dialog', (d) => d.accept());
  await p.goto(BASE + '/meet/?t=' + encodeURIComponent(token), { waitUntil: 'networkidle0' });
  await p.evaluate(() => { const b = [...document.querySelectorAll('.lang button')].find((x) => x.dataset.l === 'ru'); b.click(); });
  await p.click('#new');
  await p.waitForSelector('#title', { visible: true });
  check('«До даты» скрыто, пока нет повтора', await p.$eval('#untilBox', (e) => e.style.visibility === 'hidden'));
  check('подписи повтора на месте', (await p.$eval('#recur', (e) => e.options[3].textContent)) === 'Каждую неделю');
  await p.type('#title', 'Сайт: планёрка');
  await p.$eval('#org', (e) => { e.value = 'Сайт'; });
  await p.$eval('#orgmail', (e) => { e.value = 'site@acme.io'; });
  await p.select('#recur', 'weekly');
  check('«До даты» появилось', await p.$eval('#untilBox', (e) => e.style.visibility === ''));
  await p.screenshot({ path: SP + '/site-form.png' });
  await p.click('#go');
  await p.waitForSelector('#done', { visible: true });
  const a = await mine();
  check('создана серия', a.length > 20 && a[0].recur === 'weekly' && new Set(a.map((x) => x.uid)).size === 1);
  await p.click('#close');
  await sleep(500);
  await p.click('#next');
  await p.evaluate(() => { [...document.querySelectorAll('.ev')].find((x) => x.innerText.includes('Сайт: планёрка')).click(); });
  await p.waitForSelector('#scope', { visible: true });
  check('на сетке значок и выбор «только эта / вся серия»', await p.$eval('#recurRow', (e) => e.hidden));
  await p.screenshot({ path: SP + '/site-edit.png' });
  await p.click('#drop');
  await sleep(800);
  const b = await mine();
  check('отменена одна дата, серия жива', b.length === a.length - 1);
  await p.click('#next');
  await p.evaluate(() => { [...document.querySelectorAll('.ev')].find((x) => x.innerText.includes('Сайт: планёрка')).click(); });
  await p.waitForSelector('#scope', { visible: true });
  await p.select('#scope', 'all');
  check('для всей серии повтор виден', !(await p.$eval('#recurRow', (e) => e.hidden)));
  await p.$eval('#title', (e) => { e.value = 'Сайт: новая тема'; });
  await p.click('#go');
  await sleep(800);
  const c = await mine();
  check('тема сменилась у всех, дата-исключение осталась', c.length === b.length && c.every((m) => m.title === 'Сайт: новая тема'));
  check('время не уехало', new Date(c[0].start).getTime() === new Date(a[0].start).getTime());
  await p.click('#close');
  await sleep(400);
  await p.click('#mode');
  await sleep(300);
  check('в списке — пометка повторения', (await p.$eval('#mlist', (e) => e.innerText)).includes('↻ Каждую неделю'));
  await p.screenshot({ path: SP + '/site-list.png' });
  check('ошибок JS нет', errs.length === 0); if (errs.length) console.log(errs);
  await br.close(); console.log('ошибок:', fails); process.exit(fails ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
