CYR = dict(zip("абвгдђежзијклљмнњопрстћуфхцчџш",
               ["a","b","v","g","d","đ","e","ž","z","i","j","k","l","lj","m","n","nj","o","p","r","s","t","ć","u","f","h","c","č","dž","š"]))


def latin(s):
    out = []
    for ch in s:
        low = ch.lower()
        if low in CYR:
            t = CYR[low]
            out.append(t if ch == low else t[0].upper() + t[1:])
        else:
            out.append(ch)
    return "".join(out)


def xml_text(s):
    s = escape(s).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return s


